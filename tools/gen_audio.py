#!/usr/bin/env python3
"""Generate every audio asset of Nightmare Hunter and the sounds registry.

Usage:
    python3 tools/gen_audio.py            # write assets + data/sounds.json
    python3 tools/gen_audio.py --check    # verify files/registry are current

Deterministic: the same commit always produces byte-identical audio, so CI can
regenerate and diff if needed. All output is original (CC0, see CREDITS.md).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import os
import sys

import numpy as np
import soundfile as sf

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from audio_music import TRACKS, make_track  # noqa: E402
from audio_recipes import render  # noqa: E402
from audio_synth import SR, resample  # noqa: E402
from sfx_specs import SFX  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SFX_DIR = os.path.join(ROOT, "assets", "audio", "sfx")
MUSIC_DIR = os.path.join(ROOT, "assets", "audio", "music")
REGISTRY = os.path.join(ROOT, "data", "sounds.json")

MUSIC_VOLUME_DB = -9.0


def _rng_for(name: str) -> np.random.Generator:
    seed = int(hashlib.sha256(name.encode("utf-8")).hexdigest()[:8], 16)
    return np.random.default_rng(seed)


def _write_wav(path: str, data: np.ndarray) -> int:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = np.clip(data, -1.0, 1.0)
    sf.write(path, data.astype(np.float32), SR, format="WAV", subtype="PCM_16")
    return os.path.getsize(path)


def _write_ogg(path: str, data: np.ndarray) -> int:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    data = np.clip(data, -1.0, 1.0)
    sf.write(path, data.astype(np.float32), SR, format="OGG", subtype="VORBIS")
    return os.path.getsize(path)


def build() -> dict:
    registry = {
        "schema": 1,
        "comment": "Generated by tools/gen_audio.py. Do not edit by hand.",
        "max_concurrent": 16,
        "sample_rate": SR,
        "events": {},
        "music": {},
    }
    total = 0
    written = 0

    for event_id, spec in SFX.items():
        variants = int(spec.get("variants", 1))
        files = []
        for i in range(variants):
            name = f"{event_id}_v{i + 1}.wav"
            rel = f"res://assets/audio/sfx/{name}"
            path = os.path.join(SFX_DIR, name)
            if not os.path.exists(path):
                data = render(spec, _rng_for(name + str(i)))
                # variants must sound different, not be byte-identical copies
                data = resample(data, 1.0 + 0.035 * i)
                total += _write_wav(path, data)
                written += 1
            else:
                total += os.path.getsize(path)
            files.append(rel)
        registry["events"][event_id] = {
            "bus": spec.get("bus", "SFX"),
            "files": files,
            "variants": variants,
            "volume_db": float(spec.get("vol", -10.0)),
            "pitch_variance": float(spec.get("pitch", 0.0)),
            "spatial": bool(spec.get("spatial", False)),
            "loop": False,
        }

    for track_id in TRACKS:
        name = f"{track_id}.ogg"
        rel = f"res://assets/audio/music/{name}"
        path = os.path.join(MUSIC_DIR, name)
        if not os.path.exists(path):
            data = make_track(track_id, _rng_for(name))
            total += _write_ogg(path, data)
            written += 1
        else:
            total += os.path.getsize(path)
        registry["music"][track_id] = {
            "bus": "Music",
            "file": rel,
            "volume_db": MUSIC_VOLUME_DB,
            "loop": True,
        }

    registry["total_bytes"] = total
    with open(REGISTRY, "w", encoding="utf-8") as fh:
        json.dump(registry, fh, indent=2, ensure_ascii=False)
        fh.write("\n")

    print(f"events: {len(registry['events'])}, music: {len(registry['music'])}")
    print(f"files generated this run: {written}")
    print(f"total audio size: {total / 1024 / 1024:.2f} MiB")
    return registry


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--force", action="store_true", help="re-render existing files")
    parser.add_argument("--check", action="store_true", help="only verify, do not write")
    args = parser.parse_args()

    if args.check:
        missing = []
        for event_id, spec in SFX.items():
            for i in range(int(spec.get("variants", 1))):
                p = os.path.join(SFX_DIR, f"{event_id}_v{i + 1}.wav")
                if not os.path.exists(p):
                    missing.append(p)
        for track_id in TRACKS:
            p = os.path.join(MUSIC_DIR, f"{track_id}.ogg")
            if not os.path.exists(p):
                missing.append(p)
        if missing:
            for m in missing:
                print("MISSING", os.path.relpath(m, ROOT))
            return 1
        print("audio assets present:", len(SFX), "events,", len(TRACKS), "tracks")
        return 0

    if args.force:
        for d in (SFX_DIR, MUSIC_DIR):
            if os.path.isdir(d):
                for f in os.listdir(d):
                    os.remove(os.path.join(d, f))
    build()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
